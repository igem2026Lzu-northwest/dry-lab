*     将能量从 MeV 转换为 GeV，赋值给 TKEFLK
         TKEFLK (NPFLKA) = E_SAMP * 1.0D-3
*     计算对应的动量（中子质量 AM(8)）
         PMOFLK (NPFLKA) = SQRT ( TKEFLK (NPFLKA) *
     &                   ( TKEFLK (NPFLKA) + TWOTWO * AM (8) ) )
      ELSE
*     使用 BEAM 卡设定的能量（标准方式）
         TKEFLK (NPFLKA) = SQRT ( PBEAM**2 + AM (IONID)**2 )
     &                   - AM (IONID)
         PMOFLK (NPFLKA) = PBEAM
      END IF
*
*  --- 位置和方向：完全由 BEAMPOS 卡设置（XBEAM, YBEAM, ZBEAM, UBEAM, VBEAM, WBEAM）---
      XFLK   (NPFLKA) = XBEAM
      YFLK   (NPFLKA) = YBEAM
      ZFLK   (NPFLKA) = ZBEAM
      TXFLK  (NPFLKA) = UBEAM
      TYFLK  (NPFLKA) = VBEAM
      TZFLK  (NPFLKA) = WBEAM
*
*  --- 以下为标准模板内容，保持不变 ---
      LOFLK  (NPFLKA) = 1
      LOUSE  (NPFLKA) = 0
      KCHFLK (NPFLKA) = 0
      ECRFLK (NPFLKA) = ZERZER
      TXPOL  (NPFLKA) = -TWOTWO
      TYPOL  (NPFLKA) = +ZERZER
      TZPOL  (NPFLKA) = +ZERZER
      INFSTK (NPFLKA) = 0
      LNFSTK (NPFLKA) = 0
      ANFSTK (NPFLKA) = ZERZER
      IPRSTK (NPFLKA) = 0
      EKPSTK (NPFLKA) = ZERZER
      DO 100 ISPR = 1, MKBMX1
         SPAREK (ISPR,NPFLKA) = ZERZER
 100  CONTINUE
      DO 200 ISPR = 1, MKBMX2
         ISPARK (ISPR,NPFLKA) = 0
 200  CONTINUE
      ISPARK (MKBMX2,NPFLKA) = NPFLKA
      NPARMA = NPARMA + 1
      NUMPAR (NPFLKA) = NPARMA
      NEVENT (NPFLKA) = 0
      DFNEAR (NPFLKA) = +ZERZER
      AKNSHR (NPFLKA) = -TWOTWO
      AGESTK (NPFLKA) = +ZERZER
*
*  Calculate the total kinetic energy of the primaries: don't change
      IF ( ILOFLK (NPFLKA) .EQ. -2 .OR. ILOFLK (NPFLKA) .GT. 100000 )
     &   THEN
         TKESUM = TKESUM + TKEFLK (NPFLKA) * WTFLK (NPFLKA)
      ELSE IF ( ILOFLK (NPFLKA) .NE. 0 ) THEN
         TKESUM = TKESUM + ( TKEFLK (NPFLKA) + AMDISC (ILOFLK(NPFLKA)) )
     &          * WTFLK (NPFLKA)
      ELSE
         TKESUM = TKESUM + TKEFLK (NPFLKA) * WTFLK (NPFLKA)
      END IF
      RADDLY (NPFLKA) = ZERZER
*
*  Here we ask for the region number of the hitting point.
      CALL GEOCRS ( TXFLK (NPFLKA), TYFLK (NPFLKA), TZFLK (NPFLKA) )
      CALL GEOREG ( XFLK  (NPFLKA), YFLK  (NPFLKA), ZFLK  (NPFLKA),
     &              NRGFLK(NPFLKA), IDISC )
*  Do not change these cards:
      CALL GEOHSM ( NHSPNT (NPFLKA), 1, -11, MLATTC )
      NLATTC (NPFLKA) = MLATTC
      CMPATH (NPFLKA) = ZERZER
      CALL SOEVSV
      RETURN
*=== End of subroutine Source =========================================*
      END
